import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';

// Use an existing Playwright installation; no dashboard runtime dependency.
const modulePath=process.env.PLAYWRIGHT_MODULE_PATH;
if(!modulePath)throw new Error('Set PLAYWRIGHT_MODULE_PATH to playwright/index.mjs.');
const {chromium}=await import(pathToFileURL(modulePath).href);
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const base=process.env.DASHBOARD_URL||'http://127.0.0.1:8765';
const screenshots=process.env.QA_OUTPUT||'/private/tmp/optical-reef-qa';
await fs.mkdir(screenshots,{recursive:true});
const context=await browser.newContext({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
try{
  await page.goto(base);
  await page.getByRole('heading',{name:'Observatory overview'}).waitFor();
  assert.equal(await page.locator('#nav a').count(),11);
  assert.match(await page.locator('#overview-metrics').innerText(),/1,346\.6/);
  assert.match(await page.locator('#geometry-stats').innerText(),/54\.56/);
  await page.screenshot({path:path.join(screenshots,'overview-desktop.png'),fullPage:true});
  await page.locator('#rings').fill('3');
  assert.match(await page.locator('#aperture').getAttribute('aria-label'),/^19 /);
  await page.locator('#f2f').fill('4');
  assert.match(await page.locator('#f2f-value').innerText(),/4.00/);
  await page.reload();
  await page.locator('#rings').waitFor();
  assert.equal(await page.locator('#rings').inputValue(),'3');
  assert.equal(await page.locator('#f2f').inputValue(),'4');
  await page.locator('#reload').click();
  await page.getByRole('heading',{name:'Observatory overview'}).waitFor();
  assert.equal(await page.locator('#rings').inputValue(),'2');
  for(const id of ['propulsion','acs','power','structure','cdh','thermal','comms','payload','requirements','traceability']){
    await page.locator(`#nav a[href="#${id}"]`).click();
    await page.locator(`#nav a[href="#${id}"][aria-current="page"]`).waitFor();
    await page.locator('main h1').waitFor();
    assert.equal(await page.locator('#nav a[aria-current="page"]').getAttribute('href'),`#${id}`);
    assert.ok(await page.locator('main').innerText());
    assert.ok(!(await page.locator('main').innerText()).includes('<span class="tag'));
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${id} horizontal page overflow`);
    if(['power','payload','structure','requirements','traceability'].includes(id))await page.screenshot({path:path.join(screenshots,`${id}-desktop.png`),fullPage:true});
  }
  assert.equal(await page.locator('math').count(),12);
  await page.locator('#nav a[href="#structure"]').click();
  await page.locator('#model-canvas').waitFor();
  const before=await page.locator('.metric-value').first().innerText();
  await page.locator('[data-select-option="graphite"]').click();
  const after=await page.locator('.metric-value').first().innerText();
  assert.notEqual(before,after,'structure material changes mass');
  assert.match(await page.locator('.selected-item').innerText(),/Graphite/);
  assert.match(await page.evaluate(()=>document.activeElement.id),/^trade-/);
  await page.locator('#model-canvas').focus();
  await page.keyboard.press('ArrowRight');await page.keyboard.press('+');await page.keyboard.press('Home');
  await page.locator('[data-reset-model]').click();
  await page.locator('#nav a[href="#overview"]').click();
  await page.locator('#overview-metrics').waitFor();
  assert.doesNotMatch(await page.locator('#overview-metrics').innerText(),/1,346\.6/);
  await page.locator('#nav a[href="#payload"]').click();
  await page.locator('[data-select-option="sic"]').click();
  await page.locator('#nav a[href="#power"]').click();
  await page.locator('#nav a[href="#power"][aria-current="page"]').waitFor();
  assert.equal((await page.locator('.metric-value').nth(1).innerText()).trim(),'TBDW');
  await page.locator('.skip').focus();await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'content');
  assert.equal(await page.locator('main h1').innerText(),'Power');
  await page.locator('#reload').click();
  await page.locator('.metrics').waitFor();
  // A source-file change on reload must invalidate the saved geometry/trade preview.
  await page.route('**/data/cdh.json',async route=>{
    const response=await route.fetch();const json=await response.json();
    json.components[0].massKg+=3;json.components[0].powerW+=5;
    await route.fulfill({response,json});
  });
  await page.reload();await page.locator('.metrics').waitFor();
  await page.locator('#nav a[href="#overview"]').click();
  assert.match(await page.locator('#overview-metrics').innerText(),/1,349\.6/);
  assert.match(await page.locator('#overview-metrics').innerText(),/485\.6/);
  await page.unroute('**/data/cdh.json');
  await page.reload();await page.locator('#overview-metrics').waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(screenshots,'overview-mobile.png'),fullPage:true});
  const mobileOverflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,offenders:[...document.querySelectorAll('body *')].filter(el=>el.getBoundingClientRect().right>innerWidth+1).map(el=>({tag:el.tagName,id:el.id,className:el.className,right:el.getBoundingClientRect().right})).slice(0,10)}));
  assert.equal(mobileOverflow.scroll>mobileOverflow.width,false,`mobile overview overflow: ${JSON.stringify(mobileOverflow)}`);
  await page.locator('#rings').fill('12');await page.locator('#f2f').fill('10');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'max geometry overflow');
  const clipped=await page.locator('.metric-value').evaluateAll(elements=>elements.filter(el=>el.scrollWidth>el.clientWidth+1).map(el=>el.textContent));
  assert.deepEqual(clipped,[],'mobile metric values fit');
  await page.screenshot({path:path.join(screenshots,'maximum-mobile.png'),fullPage:true});
  await page.locator('#nav a[href="#payload"]').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile payload overflow');
  await page.screenshot({path:path.join(screenshots,'payload-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[],'browser has no console errors');
  console.log('Browser smoke checks passed: 11 pages, geometry, selections, persistence, JSON reload, models, MathML, keyboard navigation, and mobile layout.');
  console.log(`Screenshots: ${screenshots}`);
}finally{await browser.close();}
